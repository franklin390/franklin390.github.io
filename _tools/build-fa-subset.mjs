// Builds css/font-awesome-6/css/subset.css: Font Awesome 6 with ONLY the icons the page uses (the full all.css is 130 KB).
// The webfont files stay as they are. Run it again after using a new icon:  node build-fa-subset.mjs
// Usage: node build-fa-subset.mjs [--check]   (--check only reports whether the file is current, exit code 1 if not)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const TOOLS = path.dirname(fileURLToPath(import.meta.url));
const ROOT = process.env.SITE_ROOT ? path.resolve(process.env.SITE_ROOT) : path.resolve(TOOLS, '..');
const FA_DIR = path.join(ROOT, 'css/font-awesome-6/css');
export const SUBSET_FILE = path.join(FA_DIR, 'subset.css');

// where icon classes can be written: markup, scripts, dictionaries (data-i18n-html) and the site's own stylesheets
const SOURCES = ['index.html', 'js/main.js', 'js/analytics.js', 'js/i18n.js', 'js/i18n/en.js', 'js/i18n/pt.js', 'js/i18n/es.js', 'css/main.css', 'css/staff.css', 'css/base.css', 'css/vendor.css'];
const FAMILY_CLASSES = ['fa', 'fas', 'far', 'fab', 'fa-solid', 'fa-regular', 'fa-brands'];

export function usedClasses() {
  const used = new Set();
  for (const f of SOURCES) {
    const p = path.join(ROOT, f);
    if (!fs.existsSync(p)) continue;
    const text = fs.readFileSync(p, 'utf8');
    for (const m of text.matchAll(/\bfa-[a-z0-9][a-z0-9-]*/g)) used.add(m[0]);
    for (const m of text.matchAll(/class="([^"]*)"/g)) for (const c of m[1].split(/\s+/)) if (FAMILY_CLASSES.includes(c)) used.add(c);
  }
  return used;
}

/** splits a stylesheet into top-level blocks (selector/at-rule + its braces, nesting respected) */
function blocks(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const out = [];
  let depth = 0, start = 0;
  for (let i = 0; i < css.length; i++) {
    if (css[i] === '{') depth++;
    else if (css[i] === '}') { depth--; if (depth === 0) { out.push(css.slice(start, i + 1).trim()); start = i + 1; } }
  }
  return out;
}

/** does any of the site's own stylesheets (not Font Awesome's) match this pattern? */
export const SITE_CSS = ['css/main.css', 'css/staff.css', 'css/base.css', 'css/vendor.css'];
const siteCssUses = (re) => SITE_CSS.some((f) => fs.existsSync(path.join(ROOT, f)) && re.test(fs.readFileSync(path.join(ROOT, f), 'utf8')));

const classesOf = (selector) => [...selector.matchAll(/\.([A-Za-z0-9_-]+)/g)].map((m) => m[1]);

export function buildSubset() {
  const all = fs.readFileSync(path.join(FA_DIR, 'all.css'), 'utf8');
  const used = usedClasses();
  // the faces the page really uses: solid icons ("Font Awesome 6 Free", 900), the outline calendar of the certificate dates (same family, 400) and brand logos (GitHub, LinkedIn)
  const keepFace = (b) => /font-family:\s*['"]Font Awesome 6 (Free|Brands)['"]/.test(b) && /fa-(solid-900|regular-400|brands-400)\.woff2/.test(b);
  const faceName = (b) => (/fa-solid-900/.test(b) ? 'fa-solid' : /fa-regular-400/.test(b) ? 'fa-regular' : 'fa-brands');
  const kept = [];
  for (const b of blocks(all)) {
    const brace = b.indexOf('{');
    const head = b.slice(0, brace).trim();
    if (head.startsWith('@font-face')) {
      // the font files themselves are cut to the used icons by build-fonts.mjs (woff2 only: every current browser reads it)
      if (keepFace(b)) kept.push(b.replace(/src:[^;]*;/, `src:url("../webfonts/${faceName(b)}-subset.woff2") format("woff2");`));
      continue;
    }
    if (head.startsWith('@')) continue; // keyframes, media: none of them is used by the page
    // keep each selector of the rule that is made only of used classes (selectors without any .fa-class stay)
    const selectors = head.split(',').map((s) => s.trim()).filter((s) => {
      const cls = classesOf(s);
      if (!cls.length) return true;
      return cls.every((c) => used.has(c) || !/^fa/.test(c));
    });
    if (selectors.length) kept.push(selectors.join(',') + b.slice(brace));
  }
  // the site's own CSS still writes icons with the Font Awesome 4 name (the arrow of the hero buttons): same solid font under that name
  if (siteCssUses(/font-family:\s*['"]?FontAwesome['"]?\s*[;}]/i)) kept.push('@font-face{font-family:"FontAwesome";font-display:block;font-style:normal;font-weight:900;src:url("../webfonts/fa-solid-subset.woff2") format("woff2")}');
  const min = kept.join('\n').replace(/\s*\n\s*/g, '').replace(/\s*([{};:,])\s*/g, '$1').replace(/;}/g, '}');
  const banner = '/*! Font Awesome Free 6.0.0 (https://fontawesome.com) - only the icons this site uses; generated by _tools/build-fa-subset.mjs. Icons: CC BY 4.0, Fonts: SIL OFL 1.1, Code: MIT. */\n';
  return banner + min + '\n';
}

/** icon classes the page uses that the subset (or the full file) does not define */
export function missingIcons(css = fs.readFileSync(SUBSET_FILE, 'utf8')) {
  const missing = [];
  for (const c of usedClasses()) if (!FAMILY_CLASSES.includes(c) && !css.includes('.' + c)) missing.push(c);
  return missing;
}

if (process.argv[1] && import.meta.url === `file:///${process.argv[1].replace(/\\/g, '/')}`) {
  const css = buildSubset();
  if (process.argv.includes('--check')) {
    const have = fs.existsSync(SUBSET_FILE) ? fs.readFileSync(SUBSET_FILE, 'utf8') : '';
    console.log(have === css ? 'Font Awesome subset is current' : 'Font Awesome subset is out of date: run node build-fa-subset.mjs');
    process.exit(have === css ? 0 : 1);
  }
  fs.writeFileSync(SUBSET_FILE, css);
  const miss = missingIcons(css);
  console.log(`css/font-awesome-6/css/subset.css written: ${(css.length / 1024).toFixed(1)} KB for ${usedClasses().size} classes (all.css is ${(fs.statSync(path.join(FA_DIR, 'all.css')).size / 1024).toFixed(0)} KB)`);
  if (miss.length) { console.log('WARNING: not defined in Font Awesome 6.0.0: ' + miss.join(', ')); process.exit(1); }
}
